#!/usr/bin/env python3
"""Generates policies/block_destructive.rego from CRITICAL_TYPES in tf_risk_scan.py,
so the TFC gate (OPA) and the AI reviewer always agree on what "critical" means.
Run after editing CRITICAL_TYPES:  python gen_policy.py"""
import os
from tf_risk_scan import CRITICAL_TYPES

TEMPLATE = '''# GENERATED by gen_policy.py from tf_risk_scan.CRITICAL_TYPES. Do not edit by hand.
# Blocks any plan that destroys or replaces a critical (stateful / outage-causing) resource.
# Evaluated inside HCP Terraform: no inbound connectivity to your network needed.
package terraform.policies.block_destructive

import rego.v1

critical_patterns := [
{patterns}
]

is_critical(rtype) if {{
	some p in critical_patterns
	glob.match(p, [], rtype)
}}

action_name(actions) := "REPLACE" if {{
	"delete" in actions
	"create" in actions
}} else := "DESTROY"

deny contains msg if {{
	some rc in input.plan.resource_changes
	rc.mode == "managed"
	"delete" in rc.change.actions
	is_critical(rc.type)
	msg := sprintf(
		"%s of critical resource %s (reason: %s). See the tf-risk-agent comment on this run; override only if intentional.",
		[action_name(rc.change.actions), rc.address, object.get(rc, "action_reason", "not reported")],
	)
}}
'''

os.makedirs("policies", exist_ok=True)
body = ",\n".join(f'\t"{p}"' for p in CRITICAL_TYPES)
with open("policies/block_destructive.rego", "w") as fh:
    fh.write(TEMPLATE.format(patterns=body))
print(f"wrote policies/block_destructive.rego ({len(CRITICAL_TYPES)} patterns)")
